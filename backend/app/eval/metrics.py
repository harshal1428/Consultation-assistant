"""Gold-set metrics.

The auto-apply decision comes from the TypeScript fixture generated by running
the real ``evaluateLiveInstruction``. This module only aggregates those decisions
and compares the parser output with the gold slots; it never re-implements the
live gate.
"""

from __future__ import annotations

import math
import re
from collections import Counter, defaultdict
from dataclasses import dataclass
from typing import Dict, Iterable, List, Optional, Sequence

from .gold_io import GoldRow, expected_slots, numeric_value

SLOT_NAMES = ("parameter", "direction", "side", "value", "unit")
NON_COMMAND_CATEGORIES = {
    "proposal",
    "question",
    "confirm",
    "reject",
    "undo",
    "view",
    "chatter",
    "unknown",
}


def _direction_for(instruction: Dict) -> Optional[str]:
    direction = instruction.get("direction")
    if direction in ("up", "down"):
        return direction
    operation = (instruction.get("operation") or "").lower()
    if operation in {"increase", "raise", "widen", "wide"}:
        return "up"
    if operation in {"decrease", "lower", "narrow"}:
        return "down"
    return None


def _value_equal(expected: str, instruction: Dict) -> bool:
    expected_number = numeric_value(expected)
    actual = instruction.get("value")
    if expected_number is None:
        return actual is None
    if actual is None:
        return False
    return math.isclose(expected_number, float(actual), rel_tol=1e-9, abs_tol=1e-9)


def _unit_equal(expected: str, instruction: Dict) -> bool:
    actual = instruction.get("unit") or ""
    return (expected or "") == actual


def _slot_equal(name: str, expected: str, instruction: Dict) -> bool:
    if name == "parameter":
        return (expected or "") == (instruction.get("parameter") or "")
    if name == "direction":
        return (expected or "") == (_direction_for(instruction) or "")
    if name == "side":
        # The current contract does not carry a parsed side field; the gold set
        # is all blank on side, so an absent parsed side matches.
        return (expected or "") == (instruction.get("side") or "")
    if name == "value":
        return _value_equal(expected, instruction)
    if name == "unit":
        return _unit_equal(expected, instruction)
    raise ValueError(name)


def _predicted_label(decision: Dict) -> str:
    """Infer a reporting-only speech act from the parser outcome.

    This is not used for the false-commit metric. It exists so the confusion
    matrix has meaningful columns for the current system, which does not expose
    a speech-act field in its public response.
    """
    instructions = decision.get("instructions", [])
    if any(item.get("status") == "applied" for item in instructions):
        return "command"
    for item in instructions:
        reason = (item.get("reason") or "").lower()
        match = re.search(r"intent classified as ([a-z_]+)", reason)
        if match:
            label = match.group(1).rstrip("s")
            return label
    return "ignored"


def _row_failure_kind(row: GoldRow, decision: Dict) -> Optional[str]:
    applied = [item for item in decision.get("instructions", []) if item.get("status") == "applied"]
    if row.is_command:
        if not applied:
            return "missed_commit"
        expected = expected_slots(row)
        if len(applied) != len(expected):
            return "wrong_execution"
        for index, slot in enumerate(expected):
            for name in SLOT_NAMES:
                if not _slot_equal(name, slot[name], applied[index].get("instruction", {})):
                    return "wrong_execution"
        return None
    if applied:
        return "false_commit"
    return None


def _empty_slot_counts() -> Dict[str, Dict[str, int]]:
    return {name: {"correct": 0, "total": 0} for name in SLOT_NAMES}


def _summarise(rows: Sequence[GoldRow], decisions: Dict[str, Dict]) -> Dict:
    command_rows = [row for row in rows if row.is_command]
    non_command_rows = [row for row in rows if not row.is_command]
    false_commits = [
        row
        for row in non_command_rows
        if decisions.get(row.key, {}).get("would_apply_in_live", False)
    ]
    missed = [
        row
        for row in command_rows
        if not any(
            item.get("status") == "applied"
            for item in decisions.get(row.key, {}).get("instructions", [])
        )
    ]

    slots = _empty_slot_counts()
    command_slot_total = 0
    command_slot_correct = 0
    wrong_executions = []
    applied_command_rows = 0
    value_errors: List[float] = []

    for row in command_rows:
        decision = decisions.get(row.key, {})
        applied = [
            item for item in decision.get("instructions", []) if item.get("status") == "applied"
        ]
        if not applied:
            continue
        applied_command_rows += 1
        expected = expected_slots(row)
        row_wrong = False
        if len(applied) != len(expected):
            row_wrong = True
        for index, slot in enumerate(expected):
            command_slot_total += 1
            instruction = applied[index].get("instruction", {}) if index < len(applied) else {}
            row_slot_ok = True
            for name in SLOT_NAMES:
                slots[name]["total"] += 1
                if index < len(applied) and _slot_equal(name, slot[name], instruction):
                    slots[name]["correct"] += 1
                else:
                    row_slot_ok = False
            if row_slot_ok:
                command_slot_correct += 1
            else:
                row_wrong = True
            if (
                slot["unit"] == "mm"
                and instruction.get("unit") == "mm"
                and numeric_value(slot["value"]) is not None
                and instruction.get("value") is not None
            ):
                value_errors.append(
                    abs(numeric_value(slot["value"]) - float(instruction["value"]))
                )
        if row_wrong:
            wrong_executions.append(row)

    total = len(rows)
    non_command_total = len(non_command_rows)
    command_total = len(command_rows)
    per_slot = {
        name: {
            "correct": counts["correct"],
            "total": counts["total"],
            "accuracy": (counts["correct"] / counts["total"]) if counts["total"] else None,
        }
        for name, counts in slots.items()
    }
    mae = sum(value_errors) / len(value_errors) if value_errors else None
    return {
        "rows": total,
        "command_rows": command_total,
        "non_command_rows": non_command_total,
        "false_commit_rate": (len(false_commits) / non_command_total) if non_command_total else 0.0,
        "false_commit_rows": [row.key for row in false_commits],
        "false_commits": len(false_commits),
        "missed_commit_rate": (len(missed) / command_total) if command_total else 0.0,
        "missed_commit_rows": [row.key for row in missed],
        "missed_commits": len(missed),
        "applied_command_rows": applied_command_rows,
        "wrong_execution_rate": (len(wrong_executions) / command_total) if command_total else 0.0,
        "wrong_execution_rows": [row.key for row in wrong_executions],
        "wrong_executions": len(wrong_executions),
        "slot_accuracy": per_slot,
        "command_slot_accuracy": (
            command_slot_correct / command_slot_total if command_slot_total else None
        ),
        "mean_abs_value_error_mm": mae,
        "value_error_n": len(value_errors),
        "speech_act_accuracy": None,
        "speech_act_note": (
            "N/A: the current API does not expose a speech-act field; "
            "the commitment gate is a later milestone."
        ),
    }


def evaluate(rows: Sequence[GoldRow], decisions: Dict[str, Dict]) -> Dict:
    missing = [row.key for row in rows if row.key not in decisions]
    if missing:
        raise ValueError(
            "Missing live decisions for rows: " + ", ".join(missing[:10])
            + (" ..." if len(missing) > 10 else "")
        )

    overall = _summarise(rows, decisions)
    per_category = {}
    by_category = defaultdict(list)
    for row in rows:
        by_category[row.category].append(row)
    for category, category_rows in sorted(by_category.items()):
        summary = _summarise(category_rows, decisions)
        if category == "direct_command":
            per_category[category] = {
                "rows": summary["rows"],
                "missed_commit_rate": summary["missed_commit_rate"],
                "wrong_execution_rate": summary["wrong_execution_rate"],
                "slot_accuracy": summary["slot_accuracy"],
                "mean_abs_value_error_mm": summary["mean_abs_value_error_mm"],
            }
        else:
            per_category[category] = {
                "rows": summary["rows"],
                "false_commits": summary["false_commits"],
                "false_commit_rate": summary["false_commit_rate"],
                "false_commit_row_keys": summary["false_commit_rows"],
            }

    confusion = defaultdict(lambda: Counter())
    for row in rows:
        confusion[row.canonical_label][_predicted_label(decisions[row.key])] += 1

    top_failures = []
    for row in rows:
        kind = _row_failure_kind(row, decisions.get(row.key, {}))
        if not kind:
            continue
        decision = decisions[row.key]
        got = [
            {
                "status": item.get("status"),
                "reason": item.get("reason"),
                "parameter": item.get("instruction", {}).get("parameter"),
                "direction": _direction_for(item.get("instruction", {})),
                "value": item.get("instruction", {}).get("value"),
                "unit": item.get("instruction", {}).get("unit"),
            }
            for item in decision.get("instructions", [])
        ]
        top_failures.append(
            {
                "key": row.key,
                "text": row.text,
                "expected_label": row.label,
                "expected_slots": expected_slots(row),
                "failure": kind,
                "got": got,
            }
        )

    return {
        "gold_sha256": None,
        "overall": overall,
        "splits": {
            split: _summarise([row for row in rows if row.split == split], decisions)
            for split in ("dev", "test")
        },
        "per_category": per_category,
        "confusion_matrix": {
            expected: dict(sorted(predicted.items()))
            for expected, predicted in sorted(confusion.items())
        },
        "top_failures": top_failures[:20],
        "failure_count": len(top_failures),
        "speech_act_accuracy": {
            "value": None,
            "note": overall["speech_act_note"],
        },
    }
